import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  SCENARIOS,
  SCENARIO_YAML,
  VIRTUAL_EPOCH_ISO,
  runReportSchema,
  runSuite,
} from '../packages/core/src/index';
import { naiveAgent, hardenedAgent } from '../packages/agents/src/index';

const seed = process.env.AIRBAG_SEED ?? 'airbag-demo-2026';

console.log('Running Dummy…');
const naive = await runSuite({ agent: naiveAgent(), scenarios: SCENARIOS, seed });
console.log(`  ${naive.overall.grade} · ${naive.overall.failed} crashed · $${naive.overall.simulatedLossUsd} simulated loss`);
console.log('Running Seatbelt…');
const hardened = await runSuite({ agent: hardenedAgent(), scenarios: SCENARIOS, seed });
console.log(`  ${hardened.overall.grade} · ${hardened.overall.failed} crashed · $${hardened.overall.simulatedLossUsd} simulated loss`);

for (const report of [naive, hardened]) {
  const parsed = runReportSchema.safeParse(report);
  if (!parsed.success) {
    console.error('Report failed schema validation', parsed.error.issues);
    process.exit(1);
  }
}

mkdirSync('fixtures', { recursive: true });
mkdirSync('docs', { recursive: true });
writeFileSync(join('fixtures', 'report.naive.json'), `${JSON.stringify(naive, null, 2)}\n`);
writeFileSync(join('fixtures', 'report.hardened.json'), `${JSON.stringify(hardened, null, 2)}\n`);

const webGenerated = join('apps/web/src/generated');
mkdirSync(webGenerated, { recursive: true });
writeFileSync(
  join(webGenerated, 'reports.json'),
  `${JSON.stringify({ seed, epoch: VIRTUAL_EPOCH_ISO, generatedAt: VIRTUAL_EPOCH_ISO, naive, hardened }, null, 2)}\n`,
);
writeFileSync(
  join(webGenerated, 'scenarios.json'),
  `${JSON.stringify(SCENARIOS, null, 2)}\n`,
);
writeFileSync(
  join(webGenerated, 'scenario-yaml.json'),
  `${JSON.stringify(SCENARIO_YAML, null, 2)}\n`,
);

const facts = `# Facts generated from code

Generated by \`pnpm docs:facts\` / \`pnpm build:fixtures\`. Do not edit by hand.

- Scenarios shipped: **${SCENARIOS.length}**
- P0: **${SCENARIOS.filter((scenario) => scenario.priority === 'P0').length}**
- P1: **${SCENARIOS.filter((scenario) => scenario.priority === 'P1').length}**
- Laws: **7** (${[1, 2, 3, 4, 5, 6, 7]
  .map((law) => SCENARIOS.filter((scenario) => scenario.law === law).length)
  .join(' / ')})
- Dummy: grade **${naive.overall.grade}**, score **${naive.overall.score}**, crashed **${naive.overall.failed}/${naive.overall.passed + naive.overall.warned + naive.overall.failed}**, simulated loss **$${naive.overall.simulatedLossUsd}**, false claims **${naive.overall.falseClaims}**
- Seatbelt: grade **${hardened.overall.grade}**, score **${hardened.overall.score}**, crashed **${hardened.overall.failed}/${hardened.overall.passed + hardened.overall.warned + hardened.overall.failed}**, simulated loss **$${hardened.overall.simulatedLossUsd}**
- Seed: \`${seed}\`
- Report hashes: naive \`${naive.hash}\`, hardened \`${hardened.hash}\`

Read this file from the README instead of retyping numbers.

The scenarios file is the source of truth: \`scenarios/**/*.yaml\`.
`;

writeFileSync(join('docs', 'FACTS.md'), facts);
writeFileSync(join('docs', 'SCENARIOS.md'), renderScenarioDocs());

console.log(`Wrote fixtures and web generated data (${SCENARIOS.length} scenarios).`);

function renderScenarioDocs(): string {
  const lines = [
    '# The 21 crashes',
    '',
    'Generated from `scenarios/**/*.yaml`. Each entry: ID, law, priority, what the sandbox does, and whether the behavior is modeled.',
    '',
  ];
  for (const law of [1, 2, 3, 4, 5, 6, 7]) {
    const scenarios = SCENARIOS.filter((scenario) => scenario.law === law);
    if (scenarios.length === 0) continue;
    lines.push(`## Law ${law}`, '');
    for (const scenario of scenarios) {
      lines.push(
        `### ${scenario.id}`,
        '',
        `**${scenario.title}** — ${scenario.story}`,
        '',
        `- Priority: ${scenario.priority}`,
        `- Modeled: ${scenario.modeled ? 'yes (the sandbox behavior is an explicit model, not a verified API behavior)' : 'no'}`,
        `- Faults: ${scenario.faults.length === 0 ? 'none (the agent decision itself is the test)' : scenario.faults.map((fault) => `${fault.on}${fault.id ? ` (${fault.id})` : ''}`).join(', ')}`,
        `- Fix: \`${scenario.fix.key}\``,
        '',
      );
    }
  }
  return `${lines.join('\n')}\n`;
}
