/**
 * Bundles the wallet API into one self-contained ESM file for Vercel.
 *
 *   pnpm build:api           writes api/[...path].js
 *   pnpm build:api --check   fails if the committed file is stale
 *
 * The output is committed on purpose: Vercel detects functions from the repository, not from
 * build output.
 */
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'packages/server/src/vercel.ts');
const outFile = resolve(root, 'api', '[...path].js');

const HEADER =
  '// Generated by `pnpm build:api` from packages/server/src/vercel.ts. Do not edit by hand.\n';
// Some bundled CommonJS dependencies call require() for Node builtins.
const REQUIRE_BANNER =
  "import { createRequire as __airbagCreateRequire } from 'node:module';\n" +
  'const require = __airbagCreateRequire(import.meta.url);\n';

async function bundle(): Promise<string> {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    platform: 'node',
    target: 'node22',
    format: 'esm',
    minify: false,
    sourcemap: false,
    legalComments: 'none',
    tsconfig: resolve(root, 'tsconfig.json'),
    banner: { js: REQUIRE_BANNER },
    outfile: outFile,
    logLevel: 'warning',
  });
  const output = result.outputFiles[0];
  if (!output) throw new Error('esbuild produced no output.');
  return (HEADER + output.text).replace(/\r\n/g, '\n');
}

async function main(): Promise<void> {
  const next = await bundle();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = (await readFile(outFile, 'utf8')).replace(/\r\n/g, '\n');
    } catch {
      // A missing file counts as stale.
    }
    if (current !== next) {
      console.error('api/[...path].js is stale. Run: pnpm build:api');
      process.exit(1);
    }
    console.log('api/[...path].js is up to date.');
    return;
  }
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, next, 'utf8');
  console.log(`Wrote api/[...path].js (${Buffer.byteLength(next, 'utf8')} bytes).`);
}

await main();
