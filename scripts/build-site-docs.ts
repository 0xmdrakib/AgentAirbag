/**
 * Copies the published documents into apps/web/public so the static build serves them at
 * stable URLs (https://agentairbag.xyz/llms.txt, /AGENTS.md, /docs/CLAIMS.md, ...), and writes
 * /data/scenarios.yaml, all 21 scenarios in one YAML stream.
 *
 * Relative links inside the copied Markdown are rewritten to absolute URLs, because a file served
 * from the site has no neighbours: links to other published documents point at the site, images
 * point at the raw repository file, and everything else points at the repository on GitHub.
 *
 * The copies are generated and gitignored. Run by `pnpm build`.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, resolve } from 'node:path';
import { GENERATED_SITE_FILES, PUBLISHED_FILES, SITE_ORIGIN } from './site-files';

const root = resolve(import.meta.dirname, '..');
const publicDir = join(root, 'apps', 'web', 'public');
const REPO = 'https://github.com/0xmdrakib/AgentAirbag';
const RAW = 'https://raw.githubusercontent.com/0xmdrakib/AgentAirbag/main/';

function writeFile(target: string, content: string): void {
  const full = join(publicDir, target);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
}

function isRelative(href: string): boolean {
  return !/^(?:[a-z][a-z0-9+.-]*:|#|\/\/|\/)/i.test(href);
}

/** Resolve a link found in `fileDir` (a repository directory) to an absolute URL. */
function absoluteUrl(href: string, fileDir: string): string {
  const [pathPart = '', ...rest] = href.split('#');
  const hash = rest.length > 0 ? `#${rest.join('#')}` : '';
  const repoPath = posix.normalize(posix.join(fileDir, pathPart)).replace(/^\.\//, '');
  if (pathPart === '') return href;
  if (PUBLISHED_FILES.includes(repoPath)) return `${SITE_ORIGIN}${repoPath}${hash}`;
  if (/\.(png|jpe?g|gif|svg|webp)$/i.test(repoPath)) return `${RAW}${repoPath}`;
  if (pathPart.endsWith('/')) return `${REPO}/tree/main/${repoPath.replace(/\/$/, '')}${hash}`;
  return `${REPO}/blob/main/${repoPath}${hash}`;
}

function absolutize(text: string, fileDir: string): string {
  return text
    .replace(/(\]\()([^)\s]+)(\))/g, (match, open: string, href: string, close: string) =>
      isRelative(href) ? `${open}${absoluteUrl(href, fileDir)}${close}` : match,
    )
    .replace(/(src=")([^"]+)(")/g, (match, open: string, href: string, close: string) =>
      isRelative(href) ? `${open}${absoluteUrl(href, fileDir)}${close}` : match,
    );
}

function publish(file: string, text: string): string {
  if (file === 'llms.txt') return text; // already uses absolute URLs
  if (file === 'llms-full.txt') {
    // Each section came from a different directory; its marker says which.
    return text
      .split(/(?=<!-- file: )/)
      .map((section) => {
        const marker = /^<!-- file: ([^ ]+) -->/.exec(section);
        return marker ? absolutize(section, posix.dirname(marker[1] ?? '.')) : section;
      })
      .join('');
  }
  if (file.endsWith('.md')) return absolutize(text, posix.dirname(file));
  return text;
}

for (const file of PUBLISHED_FILES) {
  const text = readFileSync(join(root, file), 'utf8').replace(/\r\n/g, '\n');
  writeFile(file, publish(file, text));
}

const scenarioRoot = join(root, 'scenarios');
const documents: string[] = ['# Agent Airbag: all 21 scenarios as one YAML stream, generated by pnpm build:site'];
for (const dir of readdirSync(scenarioRoot).sort()) {
  for (const file of readdirSync(join(scenarioRoot, dir)).sort()) {
    if (!file.endsWith('.yaml')) continue;
    const body = readFileSync(join(scenarioRoot, dir, file), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    documents.push(`---\n# scenarios/${dir}/${file}\n${body}`);
  }
}
writeFile('data/scenarios.yaml', `${documents.join('\n')}\n`);

console.log(
  `Published ${PUBLISHED_FILES.length} documents and ${GENERATED_SITE_FILES.length} generated file to apps/web/public.`,
);
