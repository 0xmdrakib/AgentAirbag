/**
 * Builds llms-full.txt (the documentation set in one file) and checks that every link in
 * llms.txt points at a file that exists in this repository.
 *
 *   pnpm llms            write llms-full.txt
 *   pnpm llms --check    fail if llms-full.txt is stale or llms.txt has a dead link
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { GENERATED_SITE_FILES, PUBLISHED_FILES, SITE_ORIGIN } from './site-files';

const root = resolve(import.meta.dirname, '..');
const RAW = 'https://raw.githubusercontent.com/0xmdrakib/AgentAirbag/main/';
const TREE = 'https://github.com/0xmdrakib/AgentAirbag/tree/main/';

const SOURCES: { path: string; title: string }[] = [
  { path: 'README.md', title: 'README' },
  { path: 'AGENTS.md', title: 'AGENTS.md' },
  { path: 'docs/ARCHITECTURE.md', title: 'Architecture' },
  { path: 'docs/SCENARIOS.md', title: 'Scenarios' },
  { path: 'docs/CLAIMS.md', title: 'Claims ledger' },
  { path: 'docs/FACTS.md', title: 'Generated facts' },
  { path: 'docs/DEPLOY.md', title: 'Deploy and wallet setup' },
];

function read(path: string): string {
  return readFileSync(resolve(root, path), 'utf8').replace(/\r\n/g, '\n').trimEnd();
}

function buildFull(): string {
  const parts = [
    '# Agent Airbag: full documentation',
    '',
    '> The documentation set in one file, generated by `pnpm llms`. Index: llms.txt. Source: https://github.com/0xmdrakib/AgentAirbag',
    '',
  ];
  for (const source of SOURCES) {
    parts.push(`<!-- file: ${source.path} -->`, '', read(source.path), '', '---', '');
  }
  return `${parts.join('\n').trimEnd()}\n`;
}

function deadLinks(): string[] {
  const text = read('llms.txt');
  const dead: string[] = [];
  for (const match of text.matchAll(/\]\((https:\/\/[^)\s]+)\)/g)) {
    const url = match[1] ?? '';
    let local: string | null = null;
    if (url.startsWith(SITE_ORIGIN)) {
      // A site link must point at a file the site build publishes.
      const path = url.slice(SITE_ORIGIN.length);
      if (!PUBLISHED_FILES.includes(path) && !GENERATED_SITE_FILES.includes(path)) dead.push(url);
      else if (PUBLISHED_FILES.includes(path) && path !== 'llms-full.txt' && !existsSync(resolve(root, path))) dead.push(url);
      continue;
    }
    if (url.startsWith(RAW)) local = url.slice(RAW.length);
    else if (url.startsWith(TREE)) local = url.slice(TREE.length);
    if (local === null) continue;
    if (local === 'llms-full.txt') continue; // generated by this script
    if (!existsSync(resolve(root, local))) dead.push(url);
  }
  return dead;
}

const full = buildFull();
const target = resolve(root, 'llms-full.txt');

if (process.argv.includes('--check')) {
  const problems: string[] = [];
  const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== full) problems.push('llms-full.txt is stale. Run: pnpm llms');
  for (const url of deadLinks()) problems.push(`llms.txt links to a missing file: ${url}`);
  if (problems.length > 0) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  console.log('llms.txt links resolve and llms-full.txt is current.');
} else {
  writeFileSync(target, full);
  console.log(`Wrote llms-full.txt (${full.length} characters from ${SOURCES.length} files).`);
}
